function renderGalleryMenu(galleryMenu) {
    galleryMenu.innerHTML = [
        '<a class="site-nav__sublink" href="#gallery">All Works</a>',
        ...artworks.map(
            (artwork) =>
                `<a class="site-nav__sublink" href="#${artwork.slug}" data-gallery-target="${artwork.slug}">${artwork.title}</a>`
        )
    ].join("");
}

function renderReferences(referencesTableBody) {
    referencesTableBody.innerHTML = artworks
        .flatMap((artwork) =>
            artwork.references.map(
                (reference) => `
                    <tr>
                        <td class="references-table__artwork">${artwork.title}</td>
                        <td class="references-table__type">${reference.type}</td>
                        <td>
                            <a
                                class="references-table__link"
                                href="${reference.url}"
                                target="_blank"
                                rel="noreferrer noopener"
                            >
                                ${reference.label}
                            </a>
                            <span class="references-table__domain">${getHostLabel(reference.url)}</span>
                        </td>
                    </tr>
                `
            )
        )
        .join("");
}

function setupRevealAnimations(animatedNodes) {
    if (prefersReducedMotion.matches) {
        animatedNodes.forEach((node) => node.classList.add("is-visible"));
        return;
    }

    const observer = new IntersectionObserver(
        (entries) => {
            entries.forEach((entry) => {
                if (!entry.isIntersecting) {
                    return;
                }

                entry.target.classList.add("is-visible");
                observer.unobserve(entry.target);
            });
        },
        {
            threshold: 0.18,
            rootMargin: "0px 0px -10% 0px"
        }
    );

    animatedNodes.forEach((node) => observer.observe(node));
}

function setupNavigation({ landing, menuToggle, siteNav }) {
    const galleryDropdown = document.getElementById("galleryDropdown");
    const galleryToggle = document.getElementById("galleryDropdownToggle");

    const closeDropdown = () => {
        galleryDropdown.classList.remove("is-open");
        galleryToggle.setAttribute("aria-expanded", "false");
    };

    const closeMenus = () => {
        document.body.classList.remove("nav-open");
        menuToggle.setAttribute("aria-expanded", "false");
        closeDropdown();
    };

    menuToggle.addEventListener("click", () => {
        const isOpen = document.body.classList.toggle("nav-open");
        menuToggle.setAttribute("aria-expanded", String(isOpen));

        if (!isOpen) {
            closeDropdown();
        }
    });

    galleryToggle.addEventListener("click", () => {
        const isOpen = galleryDropdown.classList.toggle("is-open");
        galleryToggle.setAttribute("aria-expanded", String(isOpen));
    });

    siteNav.addEventListener("click", (event) => {
        const hashLink = event.target.closest('a[href^="#"]');

        if (!hashLink) {
            return;
        }

        const targetHash = hashLink.getAttribute("href");

        if (!document.body.classList.contains("gallery-open") && targetHash !== "#gallery-intro") {
            event.preventDefault();
            closeMenus();
            revealGallery(landing, { scrollTarget: targetHash });
            return;
        }

        closeMenus();
    });

    document.addEventListener("click", (event) => {
        if (!event.target.closest("#galleryDropdown")) {
            closeDropdown();
        }
    });

    document.addEventListener("keydown", (event) => {
        if (event.key !== "Escape") {
            return;
        }

        closeMenus();
    });
}

function setupActiveSections(navStateLinks) {
    const gallerySubLinks = [...document.querySelectorAll(".site-nav__sublink[data-gallery-target]")];
    const sections = [
        document.getElementById("gallery-intro"),
        ...artworks.map((artwork) => document.getElementById(artwork.slug)),
        document.getElementById("references")
    ].filter(Boolean);

    const setActiveNav = (activeId) => {
        navStateLinks.home?.classList.toggle("is-active", activeId === "gallery-intro");
        navStateLinks.references?.classList.toggle("is-active", activeId === "references");
        navStateLinks.gallery?.classList.toggle("is-active", Boolean(artworkLookup[activeId]));

        gallerySubLinks.forEach((link) => {
            link.classList.toggle("is-active", link.dataset.galleryTarget === activeId);
        });
    };

    const observer = new IntersectionObserver(
        (entries) => {
            const visibleEntry = entries
                .filter((entry) => entry.isIntersecting)
                .sort((first, second) => second.intersectionRatio - first.intersectionRatio)[0];

            if (!visibleEntry) {
                return;
            }

            setActiveNav(visibleEntry.target.id);
        },
        {
            threshold: [0.15, 0.35, 0.6]
        }
    );

    sections.forEach((section) => observer.observe(section));
}

function setupCardToggles(gallery) {
    gallery.addEventListener("click", (event) => {
        const button = event.target.closest(".card__button");

        if (!button) {
            return;
        }

        const copy = button.parentElement?.querySelector(".card__copy");

        if (!copy) {
            return;
        }

        const isExpanded = copy.classList.toggle("is-expanded");
        button.textContent = isExpanded ? "Show Less" : "Learn More";
        button.setAttribute("aria-expanded", String(isExpanded));
    });
}

function setupArtworkModals(gallery) {
    const imageModal = document.getElementById("imageModal");
    const detailsModal = document.getElementById("detailsModal");
    const modalImage = document.getElementById("modalImage");
    const detailsTitle = document.getElementById("detailsTitle");
    const detailsArtist = document.getElementById("detailsArtist");
    const detailsYear = document.getElementById("detailsYear");
    const detailsMedium = document.getElementById("detailsMedium");
    const detailsDimensions = document.getElementById("detailsDimensions");
    const detailsLocation = document.getElementById("detailsLocation");

    const openModal = (modal) => {
        [imageModal, detailsModal].forEach((modalItem) => {
            modalItem.classList.remove("is-open");
            modalItem.setAttribute("aria-hidden", "true");
        });

        modal.classList.add("is-open");
        modal.setAttribute("aria-hidden", "false");
        document.body.classList.add("modal-open");
    };

    const closeModal = (modal) => {
        modal.classList.remove("is-open");
        modal.setAttribute("aria-hidden", "true");

        if (!document.querySelector(".modal.is-open")) {
            document.body.classList.remove("modal-open");
        }
    };

    gallery.addEventListener("click", (event) => {
        const imageButton = event.target.closest(".js-open-image");
        const detailsButton = event.target.closest(".js-open-details");

        if (imageButton) {
            const artwork = artworkLookup[imageButton.dataset.artwork];

            if (!artwork) {
                return;
            }

            modalImage.src = artwork.image;
            modalImage.alt = artwork.alt;
            document.getElementById("imageModalTitle").textContent = artwork.title;
            openModal(imageModal);
            return;
        }

        if (detailsButton) {
            const artwork = artworkLookup[detailsButton.dataset.artwork];

            if (!artwork) {
                return;
            }

            detailsTitle.textContent = artwork.title;
            detailsArtist.textContent = artwork.artist;
            detailsYear.textContent = artwork.details.year;
            detailsMedium.textContent = artwork.details.medium;
            detailsDimensions.textContent = artwork.details.dimensions;
            detailsLocation.textContent = artwork.details.location;
            openModal(detailsModal);
        }
    });

    document.querySelectorAll("[data-close-modal]").forEach((closeTrigger) => {
        closeTrigger.addEventListener("click", () => {
            closeModal(imageModal);
            closeModal(detailsModal);
        });
    });

    document.addEventListener("keydown", (event) => {
        if (event.key !== "Escape") {
            return;
        }

        closeModal(imageModal);
        closeModal(detailsModal);
    });
}

function setupParallax() {
    if (prefersReducedMotion.matches) {
        return;
    }

    const parallaxImages = [...document.querySelectorAll("[data-parallax]")];

    if (!parallaxImages.length) {
        return;
    }

    let ticking = false;

    const updateParallax = () => {
        parallaxImages.forEach((image) => {
            const frame = image.closest(".artwork__frame");

            if (!frame) {
                return;
            }

            const rect = frame.getBoundingClientRect();
            const midpoint = rect.top + rect.height / 2;
            const viewportMidpoint = window.innerHeight / 2;
            const offset = (viewportMidpoint - midpoint) * 0.05;

            image.style.setProperty("--parallax-offset", `${offset.toFixed(2)}px`);
        });

        ticking = false;
    };

    const requestParallaxUpdate = () => {
        if (ticking) {
            return;
        }

        ticking = true;
        window.requestAnimationFrame(updateParallax);
    };

    updateParallax();
    window.addEventListener("scroll", requestParallaxUpdate, { passive: true });
    window.addEventListener("resize", requestParallaxUpdate);
}

function updateHeaderState(siteHeader) {
    siteHeader.classList.toggle("is-scrolled", window.scrollY > 20);
}

function revealGallery(landing, { animate = false, scrollTarget = null } = {}) {
    const shouldScroll = Boolean(scrollTarget);

    document.body.classList.add("gallery-open");

    if (animate) {
        landing.classList.add("is-leaving");

        window.setTimeout(() => {
            landing.classList.add("is-hidden");
        }, 900);
    } else {
        landing.classList.add("is-hidden");
    }

    if (!shouldScroll) {
        return;
    }

    window.setTimeout(() => {
        document.querySelector(scrollTarget)?.scrollIntoView({
            behavior: prefersReducedMotion.matches ? "auto" : "smooth",
            block: "start"
        });
    }, animate ? 180 : 40);
}

function getHostLabel(url) {
    try {
        return new URL(url).hostname.replace(/^www\./, "");
    } catch (error) {
        return url;
    }
}
