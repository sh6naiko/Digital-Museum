const prefersReducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)");
const artworkLookup = Object.fromEntries(artworks.map((artwork) => [artwork.slug, artwork]));

document.addEventListener("DOMContentLoaded", () => {
    const gallery = document.getElementById("gallery");
    const galleryMenu = document.getElementById("galleryMenu");
    const referencesTableBody = document.getElementById("referencesTableBody");
    const landing = document.getElementById("landing");
    const enterGalleryButton = document.getElementById("enterGalleryButton");
    const menuToggle = document.getElementById("menuToggle");
    const siteHeader = document.getElementById("siteHeader");
    const siteNav = document.getElementById("siteNav");

    renderGallery(gallery);
    renderGalleryMenu(galleryMenu);
    renderReferences(referencesTableBody);

    const navStateLinks = {
        home: document.querySelector('[data-nav-link="home"]'),
        gallery: document.querySelector('[data-nav-link="gallery"]'),
        references: document.querySelector('[data-nav-link="references"]')
    };

    requestAnimationFrame(() => {
        document.body.classList.add("is-ready");
    });

    const animatedNodes = [...document.querySelectorAll("[data-animate]")];
    setupRevealAnimations(animatedNodes);
    setupNavigation({ landing, menuToggle, siteNav });
    setupActiveSections(navStateLinks);
    setupCardToggles(gallery);
    setupArtworkModals(gallery);
    setupParallax();
    updateHeaderState(siteHeader);

    window.addEventListener("scroll", () => updateHeaderState(siteHeader), { passive: true });

    if (window.location.hash && window.location.hash !== "#gallery-intro") {
        revealGallery(landing, { scrollTarget: window.location.hash });
    }

    enterGalleryButton.addEventListener("click", () => {
        revealGallery(landing, {
            animate: true,
            scrollTarget: "#gallery-intro"
        });
    });
});

